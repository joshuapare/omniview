export async function captureAll(tab, base) {
  const shots = {};
  const checks = [];
  const state = () => tab.evaluate('JSON.parse(JSON.stringify(window.__mock.state))');
  const expect = (condition, message) => { if (!condition) throw new Error(message); checks.push(message); };
  const click = selector => tab.run(async ({ page }, value) => { await page.click(value); }, { args: [selector] });
  await tab.emulate({ viewport: { width: 1440, height: 900 } });
  await tab.goto(base);
  await tab.waitForSelector('[data-panel="cpu"]');
  expect(JSON.stringify((await state()).selected) === '["cpu","memory"]', 'Default CPU and memory panels');
  expect(await tab.count('input[type="checkbox"],select') === 0, 'No checkbox wall or native selects');
  expect(await tab.isVisible('#queries') === false, 'Queries hidden by default');
  shots['01-metrics-overview.png'] = await tab.screenshot({ format: 'png', fullPage: false });

  await click('#addMetric');
  expect((await state()).open === 'browser', 'Search browser opens');
  await tab.fill('#metricSearch', 'network');
  expect(await tab.count('[data-add]') === 2, 'Search returns network metrics only');
  shots['02-search-metrics.png'] = await tab.screenshot({ format: 'png', selector: '.sheet' });
  await click('[data-add="network"]');
  expect((await state()).selected.includes('network'), 'Metric adds through real input');
  expect(await tab.count('.panel') === 3, 'Additional metric creates third chart');
  expect((await state()).open === null, 'Metric browser closes after selection');
  shots['03-network-chart.png'] = await tab.screenshot({ format: 'png', selector: '.sheet' });
  await tab.hover('[data-chart="cpu"]');
  expect(await tab.isVisible('#tooltip'), 'Chart hover exposes timestamp and formatted value');
  await tab.mouseMove(10, 10);

  await click('[data-split="true"]');
  expect((await state()).split, 'Container breakdown enabled');
  expect(await tab.count('[data-panel="cpu"] .series') === 2, 'Container series stay separate');
  await click('[data-split="false"]');
  await click('[data-remove="network"]');
  expect((await state()).selected.length === 2, 'Metric chip removes selection');
  await click('#queryToggle');
  expect((await state()).queryOpen, 'Query disclosure opens');
  expect(await tab.count('.var') >= 6, 'Interpolation tokens receive distinct highlighting');
  shots['04-query-disclosure.png'] = await tab.screenshot({ format: 'png', selector: '.sheet' });
  await click('[data-edit="cpu"]');
  expect(await tab.count('textarea.query-area') === 1, 'Query editor appears only on request');
  await tab.fill('textarea.query-area', '1000 * sum(rate(container_cpu_usage_seconds_total{pod="{{pod}}"}[2m]))');
  await click('[data-edit="cpu"]');
  expect((await state()).edited.cpu.includes('[2m]'), 'Edited query persists in preview');
  await click('#queryToggle');

  await click('#sourceButton');
  expect((await state()).open === 'source', 'Source picker opens');
  await click('[data-source="Platform observability"]');
  expect((await state()).source === 'Platform observability', 'Source selection uses friendly label');
  await click('#timeButton');
  await click('[data-range="15m"]');
  expect((await state()).range === '15m', 'Time preset updates');
  expect(await tab.run(async ({ page }) => page.$eval('[data-chart="cpu"] svg', node => node.textContent.includes('09:15'))), 'Chart axis follows selected range');
  await click('#inspectorButton');
  expect((await state()).open === 'inspector', 'Inspector is a separate disclosure');
  expect((await tab.text('#popover')).includes('Simulated'), 'Inspector does not claim backend evidence');
  await tab.run(async ({ page }) => { await page.keyboard.press('Escape'); });
  expect((await state()).open === null, 'Escape closes popover');
  await click('#refreshButton');
  expect((await state()).refreshes === 1, 'Refresh control updates preview state');

  await tab.goto(base);
  await tab.emulate({ viewport: { width: 1024, height: 768 } });
  await tab.waitForSelector('[data-panel="cpu"]');
  expect(await tab.run(async ({ page }) => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)), 'Tablet has no horizontal overflow');
  shots['05-tablet.png'] = await tab.screenshot({ format: 'png', fullPage: false });
  await click('#addMetric');
  expect(await tab.run(async ({ page }) => page.evaluate(() => { const r = document.getElementById('popover').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.bottom <= innerHeight; })), 'Tablet metric browser stays inside viewport');
  await tab.run(async ({ page }) => { await page.keyboard.press('Escape'); });
  await tab.emulate({ viewport: { width: 1440, height: 900 } });
  await tab.goto(base);
  await click('[aria-label="Close drawer"]');
  expect(!(await tab.isVisible('.sheet')), 'Drawer closes to expose unchanged table layout');
  expect(await tab.count('.container') === 48, 'Illustrative ready-container indicators remain in table');
  await click('tbody tr:first-child td:first-child');
  expect(await tab.isVisible('.sheet'), 'Pod row reopens metrics drawer');
  const errors = await tab.errors();
  expect(!errors.entries.some(entry => entry.type === 'pageerror'), 'No page errors in final document');
  return { checks, shots };
}
